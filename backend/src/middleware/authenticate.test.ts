import assert from "node:assert/strict";
import { after, test } from "node:test";

import bcrypt from "bcrypt";
import express, { type RequestHandler } from "express";
import jwt from "jsonwebtoken";
import request from "supertest";

import { createAuthRouter } from "../routes/auth.js";
import * as authenticateModule from "./authenticate.js";

const authenticate = (authenticateModule as unknown as {
  authenticate: RequestHandler;
}).authenticate;
const jwtSecret = "test-only-jwt-secret-with-at-least-32-characters";
const originalJwtSecret = process.env.JWT_SECRET;
const originalJwtExpiresIn = process.env.JWT_EXPIRES_IN;

process.env.JWT_SECRET = jwtSecret;
process.env.JWT_EXPIRES_IN = "1h";

after(() => {
  if (originalJwtSecret === undefined) delete process.env.JWT_SECRET;
  else process.env.JWT_SECRET = originalJwtSecret;

  if (originalJwtExpiresIn === undefined) delete process.env.JWT_EXPIRES_IN;
  else process.env.JWT_EXPIRES_IN = originalJwtExpiresIn;
});

function createProtectedApp() {
  const app = express();
  app.get("/protected", authenticate, (req, res) => {
    res.json({ user: req.user });
  });
  return app;
}

test("authenticate accepts a token generated by the login endpoint", async () => {
  const passwordHash = await bcrypt.hash("correct-password", 4);
  const app = createProtectedApp();
  app.use(express.json());
  app.use(
    "/api/auth",
    createAuthRouter({
      findUserByEmail: async () => ({
        user_id: 42,
        username: "Aamir",
        email: "aamir@example.com",
        password_hash: passwordHash,
        google_sub: null,
        role: "admin",
        created_at: new Date("2026-10-29T12:00:00.000Z"),
      }),
    }),
  );

  const loginResponse = await request(app).post("/api/auth/login").send({
    email: "aamir@example.com",
    password: "correct-password",
  });
  const protectedResponse = await request(app)
    .get("/protected")
    .set("Authorization", `Bearer ${loginResponse.body.token}`);

  assert.equal(loginResponse.status, 200);
  assert.equal(protectedResponse.status, 200);
  assert.deepEqual(protectedResponse.body, {
    user: { userId: 42, role: "admin" },
  });
});

test("authenticate returns 401 when the token is missing", async () => {
  const response = await request(createProtectedApp()).get("/protected");

  assert.equal(response.status, 401);
  assert.deepEqual(response.body, { error: "Unauthorized" });
});

test("authenticate returns 401 for an expired token", async () => {
  const token = jwt.sign({ userId: 42, role: "user" }, jwtSecret, {
    algorithm: "HS256",
    expiresIn: -1,
  });

  const response = await request(createProtectedApp())
    .get("/protected")
    .set("Authorization", `Bearer ${token}`);

  assert.equal(response.status, 401);
  assert.deepEqual(response.body, { error: "Unauthorized" });
});

test("authenticate returns 401 for an invalid signature", async () => {
  const token = jwt.sign(
    { userId: 42, role: "user" },
    "different-test-secret-with-at-least-32-characters",
    { algorithm: "HS256", expiresIn: "1h" },
  );

  const response = await request(createProtectedApp())
    .get("/protected")
    .set("Authorization", `Bearer ${token}`);

  assert.equal(response.status, 401);
  assert.deepEqual(response.body, { error: "Unauthorized" });
});

test("authenticate rejects tokens signed with a non-HS256 algorithm", async () => {
  const token = jwt.sign({ userId: 42, role: "user" }, jwtSecret, {
    algorithm: "HS384",
    expiresIn: "1h",
  });

  const response = await request(createProtectedApp())
    .get("/protected")
    .set("Authorization", `Bearer ${token}`);

  assert.equal(response.status, 401);
  assert.deepEqual(response.body, { error: "Unauthorized" });
});

test("authenticate returns 401 for malformed authorization headers", async (t) => {
  const malformedHeaders = [
    "Basic credentials",
    "Bearer",
    "Bearer token extra-value",
    "Bearer not-a-jwt",
  ];

  for (const header of malformedHeaders) {
    await t.test(header, async () => {
      const response = await request(createProtectedApp())
        .get("/protected")
        .set("Authorization", header);

      assert.equal(response.status, 401);
      assert.deepEqual(response.body, { error: "Unauthorized" });
    });
  }
});
